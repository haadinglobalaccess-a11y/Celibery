type OrderLike = ConfirmationOrder & { _id: unknown };

/** Prepares (or, with `again`, re-prepares) the WhatsApp confirmation. Sends nothing. */
async function prepareWhatsApp(order: OrderLike, opts: { auto?: boolean; again?: boolean; by?: string }) {
  const existing = await OrderNotification.findOne({ order: order._id, channel: 'whatsapp', kind: KIND }).lean();
  if (existing && opts.auto) return existing; // automatic trigger: already prepared once
  if (existing?.status === 'sent_manual' && !opts.again)
    throw conflict('ALREADY_SENT', 'A staff member already confirmed this WhatsApp message as sent. Choose "Prepare again" to send another one.');

  const lang = langOf(order);
  const to = whatsappNumber(order.contact?.phone ?? '') ?? whatsappNumber(order.shippingAddress?.phone ?? '');
  const by = opts.by;
  if (!to) {
    const detail = 'The customer phone number is not a valid WhatsApp number';
    return OrderNotification.findOneAndUpdate(
      { order: order._id, channel: 'whatsapp', kind: KIND },
      { $set: { orderNumber: order.orderNumber, provider: 'click_to_chat', status: 'skipped', lang, to: '', message: '', lastError: detail }, $push: { history: hist('skipped', 'skipped', detail, by) } },
      { upsert: true, new: true },
    ).lean();
  }
  const { override, problems } = safeOverride((await templateOverride(TEMPLATE_KEY)) as TemplateOverride);
  const message = buildWhatsAppConfirmation(order, lang, override, await storeNameFor(lang));
  const detail = `Message prepared for +${to}. Not sent yet — a staff member must open WhatsApp and press Send.${problems.length ? ' The saved template was invalid; the default wording was used.' : ''}`;
  try {
    return await OrderNotification.findOneAndUpdate(
      { order: order._id, channel: 'whatsapp', kind: KIND },
      {
        $set: { orderNumber: order.orderNumber, provider: 'click_to_chat', status: 'prepared', lang, to, message, preparedAt: new Date(), openedAt: null, confirmedAt: null, confirmedBy: null, lastError: '' },
        $push: { history: hist(existing ? 'prepared_again' : 'prepared', 'prepared', detail, by) },
      },
      { upsert: true, new: true },
    ).lean();
  } catch (err) {
    if ((err as { code?: number }).code === 11000) return OrderNotification.findOne({ order: order._id, channel: 'whatsapp', kind: KIND }).lean();
    throw err;
  }
}

