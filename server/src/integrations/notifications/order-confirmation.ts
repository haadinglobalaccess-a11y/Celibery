/** The order fields a confirmation uses (an Order document, or the sample order for previews). */
export type ConfirmationOrder = {
  _id?: unknown;
  orderNumber: string;
  lang?: string | null;
  createdAt?: Date | string | null;
  customer?: unknown;
  contact: { name: string; email: string; phone: string };
  shippingAddress: { fullName: string; phone: string; city: string; district: string; street: string; buildingNumber?: string | null; postalCode?: string | null; shortAddress?: string | null };
  items: { name: { ar?: string | null; en?: string | null }; quantity: number; unitPrice: number; lineTotal: number }[];
  currency?: string | null;
  subtotal: number;
  discountTotal?: number | null;
  deliveryFee?: number | null;
  codFee?: number | null;
  total: number;
  vatAmount?: number | null;
  paymentMethod: string;
  status: string;
  delivery?: { trackingNumber?: string | null } | null;
};

const langOf = (o: { lang?: string | null }): Lang => (o.lang === 'en' ? 'en' : 'ar');
const money = (halalas: number) => ((halalas ?? 0) / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const itemName = (it: ConfirmationOrder['items'][number], lang: Lang) => clean(it.name?.[lang] || it.name?.[lang === 'ar' ? 'en' : 'ar'] || '');
const currencyOf = (o: ConfirmationOrder, lang: Lang) => (!o.currency || o.currency === 'SAR' ? L[lang].currency : clean(o.currency));
const orderDate = (o: ConfirmationOrder, lang: Lang) =>
  new Intl.DateTimeFormat(lang === 'ar' ? 'ar-SA-u-nu-latn-ca-gregory' : 'en-GB', { dateStyle: 'long', timeStyle: 'short', timeZone: 'Asia/Riyadh' }).format(new Date(o.createdAt ?? Date.now()));

function addressText(a: ConfirmationOrder['shippingAddress'], lang: Lang) {
  return [
    a.fullName,
    [a.street, a.buildingNumber].map(clean).filter(Boolean).join(' '),
    a.district,
    [a.city, a.postalCode].map(clean).filter(Boolean).join(' '),
    a.shortAddress,
  ]
    .map(clean)
    .filter(Boolean)
    .join(lang === 'ar' ? '، ' : ', ');
}

/** "• Name × 2 — 1,234.00 SAR" lines; at most `max` items, then "+ N more". */
function productLines(o: ConfirmationOrder, lang: Lang, max = 20) {
  const cur = currencyOf(o, lang);
  const lines = o.items.slice(0, max).map((it) => `• ${itemName(it, lang)} × ${it.quantity} — ${money(it.lineTotal)} ${cur}`);
  if (o.items.length > max) lines.push(L[lang].more(o.items.length - max));
  return lines.join('\n');
}

/** Values of every supported {{variable}} for this order. */
export function confirmationVars(o: ConfirmationOrder, lang: Lang, storeName?: string): Record<string, string> {
  const f = L[lang];
  return {
    customer_name: clean(o.contact.name) || clean(o.shippingAddress.fullName),
    order_number: clean(o.orderNumber),
    order_date: orderDate(o, lang),
    order_total: money(o.total),
    currency: currencyOf(o, lang),
    payment_method: f.pay[o.paymentMethod] ?? clean(o.paymentMethod),
    order_status: f.status[o.status] ?? clean(o.status),
    products: productLines(o, lang),
    shipping_address: addressText(o.shippingAddress, lang),
    tracking_number: clean(o.delivery?.trackingNumber) || f.noTracking,
    store_name: clean(storeName) || f.store,
  };
}

/**
 * The admin template if it is valid, otherwise the built-in wording — a template saved before a
 * rule changed (or edited directly in the database) can never produce a broken message.
 */
export function safeOverride(o: TemplateOverride): { override: TemplateOverride; problems: string[] } {
  if (!o) return { override: null, problems: [] };
  const errors = validateOverride(templateDef(TEMPLATE_KEY)!, o);
  const problems = Object.entries(errors).map(([k, v]) => `${k}: ${v.join('; ')}`);
  return problems.length ? { override: null, problems } : { override: o, problems };
}

export function buildConfirmationEmail(o: ConfirmationOrder, lang: Lang, override: TemplateOverride, link: string, storeName?: string) {
  const def = templateDef(TEMPLATE_KEY)!;
  const f = L[lang];
  const v = confirmationVars(o, lang, storeName);
  const c = resolveContent(def, lang, override);
  const subject = fill(c.subject, v).replace(/[\r\n]+/g, ' ').trim();
  const body = fill(c.body, v);
  const start = lang === 'ar' ? 'right' : 'left';
  const end = lang === 'ar' ? 'left' : 'right';
  const cur = currencyOf(o, lang);
  const amt = (h: number) => `<span dir="ltr">${esc(money(h))} ${esc(cur)}</span>`;
  const cell = 'padding:8px 6px;border-bottom:1px solid #eee;vertical-align:top';
  const items = o.items
    .map((it) => `<tr><td align="${start}" style="${cell}">${esc(itemName(it, lang))}</td><td align="center" style="${cell}">${it.quantity}</td><td align="${end}" style="${cell};white-space:nowrap">${amt(it.lineTotal)}</td></tr>`)
    .join('');
  const totals: [string, string][] = [[f.subtotal, amt(o.subtotal)]];
  if (o.discountTotal) totals.push([f.discount, `- ${amt(o.discountTotal)}`]);
  totals.push([f.shipping, o.deliveryFee ? amt(o.deliveryFee) : esc(f.free)]);
  if (o.codFee) totals.push([f.codFee, amt(o.codFee)]);
  const totalRows = totals.map(([k, val]) => `<tr><td colspan="2" align="${start}" style="padding:4px 6px;color:#555">${esc(k)}</td><td align="${end}" style="padding:4px 6px;white-space:nowrap">${val}</td></tr>`).join('');
  const grand = `<tr><td colspan="2" align="${start}" style="padding:10px 6px;border-top:2px solid #111;font-weight:bold">${esc(f.total)}</td><td align="${end}" style="padding:10px 6px;border-top:2px solid #111;font-weight:bold;white-space:nowrap">${amt(o.total)}</td></tr>`;
  const vat = o.vatAmount ? `<tr><td colspan="3" align="${start}" style="padding:0 6px 8px;color:#777;font-size:12px">${esc(f.vat)}: ${amt(o.vatAmount)}</td></tr>` : '';
  const details: [string, string][] = [
    [f.orderNumber, `<strong dir="ltr">${esc(v.order_number)}</strong>`],
    [f.date, esc(v.order_date)],
    [f.payment, esc(v.payment_method)],
    [f.orderStatus, esc(v.order_status)],
    [f.shipTo, esc(v.shipping_address)],
    [f.tracking, o.delivery?.trackingNumber ? `<span dir="ltr">${esc(v.tracking_number)}</span>` : `<span style="color:#777">${esc(v.tracking_number)}</span>`],
  ];
  const detailRows = details.map(([k, val]) => `<tr><td align="${start}" style="padding:4px 6px;color:#555;white-space:nowrap;vertical-align:top">${esc(k)}</td><td align="${start}" style="padding:4px 6px">${val}</td></tr>`).join('');
  const html = layout(
    lang,
    `${paragraphs(body)}
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:16px 0;font-size:14px">${detailRows}</table>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:16px 0;font-size:14px;border-collapse:collapse">
<tr><th align="${start}" style="padding:8px 6px;border-bottom:2px solid #111">${esc(f.product)}</th><th align="center" style="padding:8px 6px;border-bottom:2px solid #111">${esc(f.qty)}</th><th align="${end}" style="padding:8px 6px;border-bottom:2px solid #111">${esc(f.amount)}</th></tr>
${items}${totalRows}${grand}${vat}</table>${button(link, f.view)}`,
  );
  const text = [
    body.trim(),
    '',
    `${f.orderNumber}: ${v.order_number}`,
    `${f.date}: ${v.order_date}`,
    `${f.payment}: ${v.payment_method}`,
    `${f.orderStatus}: ${v.order_status}`,
    `${f.shipTo}: ${v.shipping_address}`,
    `${f.tracking}: ${v.tracking_number}`,
    '',
    productLines(o, lang, 100),
    '',
    `${f.subtotal}: ${money(o.subtotal)} ${cur}`,
    ...(o.discountTotal ? [`${f.discount}: -${money(o.discountTotal)} ${cur}`] : []),
    `${f.shipping}: ${o.deliveryFee ? `${money(o.deliveryFee)} ${cur}` : f.free}`,
    ...(o.codFee ? [`${f.codFee}: ${money(o.codFee)} ${cur}`] : []),
    `${f.total}: ${money(o.total)} ${cur}`,
    '',
    link,
  ].join('\n');
  return { subject, html, text };
}

/** The prepared WhatsApp message: plain text, at most 3 blank-line-separated paragraphs in a row. */
export function buildWhatsAppConfirmation(o: ConfirmationOrder, lang: Lang, override: TemplateOverride, storeName?: string) {
  const c = resolveContent(templateDef(TEMPLATE_KEY)!, lang, override);
  const text = fill(c.whatsapp, confirmationVars(o, lang, storeName));
  const lines = text.split(/\r?\n/).map((l) => l.replace(CONTROL, ' ').replace(/[ \t]+$/g, ''));
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim().slice(0, 3000);
}

/** Link sent in the email: the account page for customers, the order tracking page for guests. */
export function confirmationLink(o: { orderNumber: string; lang?: string | null; customer?: unknown }) {
  const lang = langOf(o);
  return o.customer ? `${env.PUBLIC_SITE_URL}/${lang}/account/orders/${o.orderNumber}` : `${env.PUBLIC_SITE_URL}/${lang}/track?order=${encodeURIComponent(o.orderNumber)}`;
}

async function storeNameFor(lang: Lang) {
  const s = await getSettings();
  return (s?.business?.name as { ar?: string; en?: string } | undefined)?.[lang] || L[lang].store;
}

async function sendSmtp(smtp: SmtpConfig, to: string, content: { subject: string; html: string; text: string }) {
  await smtpTransport(smtp).sendMail({ from: smtpFrom(smtp), replyTo: smtp.replyTo || undefined, to, subject: content.subject, html: content.html, text: content.text });
}

const hist = (action: string, status: string, detail = '', by?: string) => ({ at: new Date(), action, status, detail: detail.slice(0, 500), ...(by ? { by } : {}) });

