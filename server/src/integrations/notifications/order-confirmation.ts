/**
 * Order confirmation — one email and one prepared WhatsApp message per order.
 *
 * When: an order counts as successfully placed once it is CONFIRMED — a cash-on-delivery order
 * right after it is created, an online payment once the gateway confirms the payment (a card order
 * that is never paid gets no confirmation). Called after the order is saved, never inside the
 * order transaction, and it never throws: a notification problem can not fail or duplicate an order.
 *
 * Idempotency: the unique (order, channel, kind) record is created with $setOnInsert, so a second
 * trigger (webhook replay, admin confirm, resend button) finds the existing record and does nothing.
 * Sending again is only possible through the explicit admin "send again" action.
 *
 * Reliability: the email is attempted immediately and, on failure, retried by the scheduled job
 * (jobs.ts → runReservationJob, every 5 minutes) with back-off, up to maxAttempts. A worker claims
 * a record atomically (status → "sending" with a lock), so two workers never send the same email.
 *
 * Content: the admin-edited template "order.confirmation" (Settings → Notifications → Message
 * templates; built-in defaults otherwise). Values and template text are HTML-escaped; the order
 * summary (items, totals, payment method, address) is generated by the system and cannot be removed.
 * No payment credentials are ever included — only the payment method name.
 */

