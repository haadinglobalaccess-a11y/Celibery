const TEMPLATE_KEY = 'order.confirmation';
const LOCK_MS = 2 * 60_000;
/** Minutes to wait after the 1st, 2nd, 3rd … failed attempt. */
const BACKOFF_MIN = [1, 5, 15, 60, 180];

