async function orderOr404(orderId: string) {
  const order = await Order.findById(orderId).lean();
  if (!order) throw notFound('Order');
  return order as unknown as OrderLike & { status: string };
}

/** Sends the confirmation email now (first send, retry of a failed one, or — with `resend` — another copy). */
export async function adminSendConfirmationEmail(orderId: string, by: string, opts: { resend?: boolean }) {
  const order = await orderOr404(orderId);
  if (!confirmedLike(order.status)) throw unprocessable('ORDER_NOT_CONFIRMED', 'Only confirmed orders get an order confirmation (this order is not paid / confirmed).');
  const to = clean(order.contact?.email).toLowerCase();
  if (!to) throw unprocessable('NO_EMAIL', 'This order has no email address.');
  const base = { order: order._id, channel: 'email', kind: KIND };
  let rec = await OrderNotification.findOne(base).lean();
  if (!rec) {
    try {
      await OrderNotification.create({ ...base, orderNumber: order.orderNumber, provider: 'smtp', status: 'pending', lang: langOf(order), to, nextAttemptAt: new Date(), history: [hist('send_requested', 'pending', '', by)] });
    } catch (err) {
      if ((err as { code?: number }).code !== 11000) throw err;
      throw conflict('IN_PROGRESS', 'The confirmation email is already being sent. Reload in a moment.');
    }
  } else {
    if (rec.status === 'sending' && rec.lockedUntil && rec.lockedUntil > new Date()) throw conflict('IN_PROGRESS', 'The confirmation email is being sent right now.');
    if (rec.status === 'sent' && !opts.resend)
      throw conflict('ALREADY_SENT', `The confirmation email was already sent to ${rec.to}${rec.sentAt ? ` on ${rec.sentAt.toISOString().slice(0, 16).replace('T', ' ')} UTC` : ''}. Tick "send another copy" to send it again.`);
    // Conditional on the status we looked at: a double click can only win once.
    rec = await OrderNotification.findOneAndUpdate(
      { _id: rec._id, status: rec.status },
      { $set: { status: 'pending', to, attempts: 0, nextAttemptAt: new Date(), lockedUntil: null, lastError: '' }, $push: { history: hist(rec.status === 'sent' ? 'resend_requested' : 'send_requested', 'pending', '', by) } },
      { new: true },
    ).lean();
    if (!rec) throw conflict('IN_PROGRESS', 'The confirmation email was just changed by someone else. Reload and try again.');
  }
  const id = (await OrderNotification.findOne(base).select('_id').lean())!._id;
  await processConfirmationEmail(id);
  return orderNotificationsView(orderId);
}

export async function adminPrepareWhatsApp(orderId: string, by: string, opts: { again?: boolean }) {
  const order = await orderOr404(orderId);
  if (!confirmedLike(order.status)) throw unprocessable('ORDER_NOT_CONFIRMED', 'Only confirmed orders get an order confirmation.');
  await prepareWhatsApp(order, { again: opts.again, by });
  return orderNotificationsView(orderId);
}

/** Staff opened WhatsApp with the prepared message. Recorded — but this is NOT a delivery. */
export async function adminWhatsAppOpened(orderId: string, by: string) {
  const base = { order: orderId, channel: 'whatsapp', kind: KIND };
  const h = hist('opened', 'opened', 'WhatsApp opened with the prepared message — not confirmed as sent', by);
  const r = await OrderNotification.findOneAndUpdate({ ...base, status: { $in: ['prepared', 'opened'] } }, { $set: { status: 'opened', openedAt: new Date() }, $push: { history: h } }, { new: true }).lean();
  if (!r) {
    const any = await OrderNotification.findOneAndUpdate({ ...base, status: 'sent_manual' }, { $push: { history: { ...h, status: 'sent_manual' } } }).lean();
    if (!any) throw unprocessable('NOT_PREPARED', 'Prepare the WhatsApp message first.');
  }
  return orderNotificationsView(orderId);
}

/** A staff member confirms they pressed Send in WhatsApp (WhatsApp itself does not report it). */
export async function adminWhatsAppConfirmSent(orderId: string, by: string) {
  const r = await OrderNotification.findOneAndUpdate(
    { order: orderId, channel: 'whatsapp', kind: KIND, status: { $in: ['prepared', 'opened'] } },
    { $set: { status: 'sent_manual', confirmedAt: new Date(), confirmedBy: by }, $push: { history: hist('confirmed_sent', 'sent_manual', 'Marked as sent by a staff member (WhatsApp does not confirm delivery without the official API)', by) } },
    { new: true },
  ).lean();
  if (!r) {
    const cur = await OrderNotification.findOne({ order: orderId, channel: 'whatsapp', kind: KIND }).select('status').lean();
    if (cur?.status === 'sent_manual') throw conflict('ALREADY_SENT', 'This WhatsApp message is already marked as sent.');
    throw unprocessable('NOT_PREPARED', 'Prepare the WhatsApp message first.');
  }
  return orderNotificationsView(orderId);
}

/** Everything the order page shows about the confirmation (no secrets). */
export async function orderNotificationsView(orderId: string) {
  const order = await orderOr404(orderId);
  const [recs, settings, smtp] = await Promise.all([
    OrderNotification.find({ order: order._id, kind: KIND }).populate('history.by', 'name').populate('confirmedBy', 'name').lean(),
    getSettings(),
    activeSmtp(),
  ]);
  const email = recs.find((r) => r.channel === 'email') ?? null;
  const wa = recs.find((r) => r.channel === 'whatsapp') ?? null;
  const on = settings?.orderNotifications;
  return {
    orderConfirmed: confirmedLike(order.status),
    config: {
      emailEnabled: settings?.notifications?.emailOrderUpdates !== false && on?.confirmationEmail !== false,
      smtpConfigured: Boolean(smtp),
      whatsappEnabled: on?.whatsappPrepare !== false,
      businessNumber: on?.whatsappBusinessNumber ?? '',
      /** No official WhatsApp Business Platform integration is active for confirmations. */
      whatsappApi: false,
    },
    email: email
      ? { status: email.status, to: email.to, subject: email.subject, attempts: email.attempts, maxAttempts: email.maxAttempts, lastError: email.lastError, sentAt: email.sentAt, nextAttemptAt: email.nextAttemptAt, history: email.history }
      : null,
    whatsapp: wa
      ? {
          status: wa.status,
          to: wa.to,
          message: wa.message,
          link: wa.to && wa.message ? clickToChat.link(wa.to, wa.message) : null,
          preparedAt: wa.preparedAt,
          openedAt: wa.openedAt,
          confirmedAt: wa.confirmedAt,
          confirmedBy: wa.confirmedBy,
          lastError: wa.lastError,
          history: wa.history,
        }
      : null,
  };
}

