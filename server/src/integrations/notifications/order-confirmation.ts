/** True when the order is in a state where it was successfully placed. */
const confirmedLike = (status: string) => ['confirmed', 'processing', 'shipped', 'delivered'].includes(status);

/**
 * Queues the order confirmation for an order that was just confirmed. Never throws. Calling it
 * again for the same order does nothing (idempotent). `link` may carry the guest's private order
 * link for the immediate attempt; it is never stored.
 */
export async function queueOrderConfirmation(orderId: unknown, opts: { link?: string } = {}) {
  try {
    const order = await Order.findById(orderId).lean();
    if (!order || !confirmedLike(order.status)) return;
    const settings = await getSettings();
    const on = settings?.orderNotifications;
    const lang = langOf(order);
    if (settings?.notifications?.emailOrderUpdates !== false && on?.confirmationEmail !== false) {
      const to = clean(order.contact?.email).toLowerCase();
      const status = to ? 'pending' : 'skipped';
      const detail = to ? '' : 'The order has no email address';
      try {
        const r = await OrderNotification.updateOne(
          { order: order._id, channel: 'email', kind: KIND },
          { $setOnInsert: { orderNumber: order.orderNumber, provider: 'smtp', status, lang, to, nextAttemptAt: to ? new Date() : null, lastError: detail, history: [hist(to ? 'queued' : 'skipped', status, detail)] } },
          { upsert: true },
        );
        if (r.upsertedId && to) void processConfirmationEmail(r.upsertedId, { link: opts.link });
      } catch (err) {
        if ((err as { code?: number }).code !== 11000) throw err; // a parallel trigger created it
      }
    }
    if (on?.whatsappPrepare !== false) await prepareWhatsApp(order, { auto: true });
  } catch (err) {
    logger.error('queueOrderConfirmation failed', { err: String(err) });
  }
}

/**
 * Attempts one queued/failed confirmation email. Claims it atomically, so concurrent callers
 * (immediate attempt, scheduled retry, admin button) never send it twice. Returns the record.
 */
export async function processConfirmationEmail(id: unknown, opts: { link?: string } = {}) {
  const now = new Date();
  const claimed = await OrderNotification.findOneAndUpdate(
    {
      _id: id,
      channel: 'email',
      $or: [
        { status: { $in: ['pending', 'failed'] }, nextAttemptAt: { $ne: null, $lte: now } },
        { status: 'sending', lockedUntil: { $lte: now } },
      ],
    },
    { $set: { status: 'sending', lockedUntil: new Date(now.getTime() + LOCK_MS) }, $inc: { attempts: 1 } },
    { new: true },
  );
  if (!claimed) return OrderNotification.findById(id).lean();

  const finish = (set: Record<string, unknown>, h: ReturnType<typeof hist>) =>
    OrderNotification.findOneAndUpdate({ _id: claimed._id, status: 'sending' }, { $set: { lockedUntil: null, ...set }, $push: { history: h } }, { new: true }).lean();

  const order = await Order.findById(claimed.order).lean();
  if (!order) return finish({ status: 'failed', nextAttemptAt: null, lastError: 'Order not found' }, hist('attempt_failed', 'failed', 'Order not found'));
  const to = clean(order.contact?.email).toLowerCase();
  if (!to) return finish({ status: 'skipped', nextAttemptAt: null, lastError: 'The order has no email address' }, hist('skipped', 'skipped', 'The order has no email address'));

  const smtp = await activeSmtp();
  if (!smtp) {
    const detail = 'Email (SMTP) not configured or disabled — use "Send now" once it is set up';
    await Notification.create({ channel: 'email', to, template: TEMPLATE_KEY, order: order._id, status: 'skipped', detail });
    return finish({ status: 'skipped', nextAttemptAt: null, lastError: detail }, hist('skipped', 'skipped', detail));
  }

  const lang = (claimed.lang as Lang) ?? langOf(order);
  try {
    const { override, problems } = safeOverride((await templateOverride(TEMPLATE_KEY)) as TemplateOverride);
    const content = buildConfirmationEmail(order as unknown as ConfirmationOrder, lang, override, opts.link || confirmationLink(order), await storeNameFor(lang));
    await sendSmtp(smtp, to, content);
    await Notification.create({ channel: 'email', to, template: TEMPLATE_KEY, order: order._id, status: 'sent' });
    const note = `Accepted by the mail server ${smtp.host} (attempt ${claimed.attempts})${problems.length ? ` — the saved template was invalid, the default wording was used (${problems.join(' | ')})` : ''}`;
    return finish({ status: 'sent', to, subject: content.subject, sentAt: new Date(), nextAttemptAt: null, lastError: '' }, hist('sent', 'sent', note));
  } catch (err) {
    const detail = smtpError(err, smtp);
    logger.warn('Order confirmation email failed', { orderNumber: order.orderNumber, attempt: claimed.attempts, err: detail });
    await Notification.create({ channel: 'email', to, template: TEMPLATE_KEY, order: order._id, status: 'failed', detail: detail.slice(0, 300) }).catch(() => undefined);
    const final = claimed.attempts >= (claimed.maxAttempts ?? 5);
    const wait = BACKOFF_MIN[Math.min(claimed.attempts - 1, BACKOFF_MIN.length - 1)] * 60_000;
    return finish(
      { status: 'failed', to, lastError: detail, nextAttemptAt: final ? null : new Date(Date.now() + wait) },
      hist('attempt_failed', 'failed', `Attempt ${claimed.attempts}: ${detail}${final ? ' — no more automatic retries' : ''}`),
    );
  }
}

/** Scheduled retry of failed / interrupted confirmation emails (jobs.ts). */
export async function retryOrderNotifications(limit = 20) {
  const now = new Date();
  const due = await OrderNotification.find({
    channel: 'email',
    $or: [
      { status: { $in: ['pending', 'failed'] }, nextAttemptAt: { $ne: null, $lte: now } },
      { status: 'sending', lockedUntil: { $lte: now } },
    ],
  })
    .sort({ nextAttemptAt: 1 })
    .limit(limit)
    .select('_id')
    .lean();
  let sent = 0;
  let failed = 0;
  for (const d of due) {
    const r = await processConfirmationEmail(d._id);
    if (r?.status === 'sent') sent++;
    else if (r?.status === 'failed') failed++;
  }
  return { due: due.length, sent, failed };
}

