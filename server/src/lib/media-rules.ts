import { canonicalMime, kindOfMime } from './media-sniff';

/**
 * Upload rules shared by the media service and its unit tests (pure, no I/O).
 */
export type PartInput = { role: string; contentType: string; size: number; width?: number };
export type UploadLimits = { imageBytes: number; videoBytes: number };

const MB = 1024 * 1024;

/** Validates an upload request; returns a human-readable problem or null. */
export function validateUploadParts(kind: 'image' | 'video', parts: PartInput[], limits: UploadLimits): string | null {
  if (!parts.length) return 'No file to upload';
  if (parts.length > 6) return 'Too many files in one upload';
  const roles = new Set<string>();
  for (const p of parts) {
    if (roles.has(p.role)) return `Duplicate part ${p.role}`;
    roles.add(p.role);
    if (!/^(original|poster|w\d{2,4})$/.test(p.role)) return `Unknown part ${p.role}`;
    const mime = canonicalMime(p.contentType);
    const k = kindOfMime(mime);
    const expected = p.role === 'original' ? kind : 'image';
    if (k !== expected) {
      return p.role === 'original'
        ? `This file type (${mime || 'unknown'}) is not accepted for ${kind}s. Images: JPEG, PNG, WebP, AVIF, GIF. Videos: MP4, WebM.`
        : `The ${p.role} file must be an image`;
    }
    if (p.role === 'poster' && kind !== 'video') return 'Only videos have a poster image';
    if (!Number.isInteger(p.size) || p.size <= 0) return 'File is empty';
    const partKind = p.role === 'original' ? kind : 'image';
    const max = partKind === 'image' ? limits.imageBytes : limits.videoBytes;
    if (p.size > max) return `File is too large (maximum ${Math.round(max / MB)} MB for ${partKind}s)`;
  }
  if (!roles.has('original')) return 'The original file is missing';
  return null;
}

/** Storage keys are generated by the server; this also blocks traversal or foreign paths. */
export function safeKey(key: string): string {
  if (!/^media\/[0-9]{4}\/[0-9]{2}\/[a-z]+-[A-Za-z0-9_-]{8,64}(?:-w\d{2,4})?\.[a-z0-9]{2,5}$/.test(key)) throw new Error('Invalid storage key');
  return key;
}
