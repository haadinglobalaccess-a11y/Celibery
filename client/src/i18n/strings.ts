/** «ضمان سنة» / «ضمان سنتين» / «ضمان 6 أشهر» / «ضمان 18 شهراً». */
function arWarranty(m: number): string {
  const y = m / 12;
  const unit = m >= 12 && m % 12 === 0 ? (y === 1 ? 'سنة' : y === 2 ? 'سنتين' : y <= 10 ? `${y} سنوات` : `${y} سنة`) : m === 1 ? 'شهر' : m === 2 ? 'شهرين' : m <= 10 ? `${m} أشهر` : `${m} شهراً`;
  return `ضمان ${unit}`;
}

