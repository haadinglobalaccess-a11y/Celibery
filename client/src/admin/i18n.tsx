const DICTS: Record<AdminLang, Dict> = { en, ar };

const LangCtx = createContext<AdminLang>('en');

export function AdminLangScope({ lang, children }: { lang: AdminLang; children: ReactNode }) {
  return <LangCtx.Provider value={lang}>{children}</LangCtx.Provider>;
}

export function useAdminLang() {
  return useContext(LangCtx);
}

/** Dictionary + formatters for the active admin language. Western digits and Gregorian dates in both languages. */
export function useAT() {
  const lang = useContext(LangCtx);
  return { lang, t: DICTS[lang], ...formatters(lang) };
}

export function formatters(lang: AdminLang) {
  const locale = lang === 'ar' ? 'ar-u-nu-latn-ca-gregory' : 'en-GB';
  const num = new Intl.NumberFormat('en-US');
  const money = new Intl.NumberFormat('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const dateTime = new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' });
  const dateOnly = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric' });
  const dayMonth = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short' });
  return {
    n: (v: number) => num.format(v),
    /** Halalas → "SAR 1,234.00" (English) / "1,234.00 ر.س" (Arabic). */
    sar: (halalas: number | null | undefined) => {
      if (halalas == null) return '—';
      const v = money.format(halalas / 100);
      return lang === 'ar' ? `${v} ر.س` : `SAR ${v}`;
    },
    dt: (iso?: string | Date | null) => (iso ? dateTime.format(new Date(iso)) : '—'),
    d: (iso?: string | Date | null) => (iso ? dateOnly.format(new Date(iso)) : '—'),
    dm: (iso?: string | Date | null) => (iso ? dayMonth.format(new Date(iso)) : '—'),
  };
}

const STORE_KEY = 'celibery.admin.lang';
export function readAdminLang(): AdminLang {
  try {
    const v = localStorage.getItem(STORE_KEY);
    return v === 'ar' || v === 'en' ? v : 'en';
  } catch {
    return 'en';
  }
}
export function saveAdminLang(lang: AdminLang) {
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch {
    /* storage unavailable: preference lasts for this session */
  }
}
